import {createHash} from 'node:crypto';

function canonical(value) {
  if(Array.isArray(value))return value.map(canonical);
  if(value&&typeof value==='object')return Object.fromEntries(Object.keys(value).sort().filter(k=>value[k]!==undefined).map(k=>[k,canonical(value[k])]));
  return value;
}
export function snapshotBanks(banks) {
  const snapshot={};
  banks.forEach((bank,type)=>{
    for(const question of bank){
      const {slot,variations,retired,reviewStatus,status,...template}=question;
      for(const [variation,content] of variations.entries()){
        // Challenge labels are selection metadata, not changes to the question or marking.
        delete template.challengeLevel;
        if(template.tags)template.tags=template.tags.filter(tag=>!tag.startsWith('challenge:'));
        const data=JSON.stringify(canonical({...template,...content}));
        snapshot[`${type}:${slot}:${variation}`]={fingerprint:createHash('sha256').update(data).digest('hex'),focus:question.focus,marks:content.parts.reduce((sum,p)=>sum+p.marks,0)};
      }
    }
  });
  return snapshot;
}
export function nextHistory(history,snapshot) {
  const latest=Math.max(...Object.keys(history).map(Number)),previous=history[latest];
  for(const key of Object.keys(snapshot)){
    const slot=key.slice(0,key.lastIndexOf(':')+1);
    const reusedSlot=!Object.keys(previous).some(address=>address.startsWith(slot))&&
      Object.values(history).some(revision=>Object.keys(revision).some(address=>address.startsWith(slot)));
    if(reusedSlot||!previous[key]&&Object.values(history).some(revision=>revision[key]))
      throw Error(`Cannot reuse removed question/variation address ${key}. Allocate a new slot instead.`);
  }
  // Additions at unused addresses cannot invalidate an existing valid code.
  const altered=Object.entries(previous).some(([key,digest])=>snapshot[key]?.fingerprint!==digest.fingerprint);
  const version=altered?latest+1:latest;
  if(version>127)throw Error('Question revision capacity reached; extend the codec before publishing.');
  return {...history,[version]:snapshot};
}
export function compatibilityModule(history) {
  const current=Math.max(...Object.keys(history).map(Number)),latest=history[current],revisions={};
  for(const [version,snapshot] of Object.entries(history)){
    // 1 = unchanged and available; 0 = changed or removed. Absent = never existed.
    revisions[version]=Object.fromEntries(Object.entries(snapshot).map(([key,digest])=>[key,latest[key]?.fingerprint===digest.fingerprint?1:0]));
  }
  return '// Generated by scripts/question-codes.mjs. Do not edit by hand.\n'+
    `export const BANK_VERSION=${current};\nexport const revisions=${JSON.stringify(revisions,null,2)};\n`+
    `export const revisionDetails=${JSON.stringify(Object.fromEntries(Object.entries(history).map(([version,entries])=>[version,Object.fromEntries(Object.entries(entries).map(([key,entry])=>[key,[entry.focus,entry.marks]]))])),null,2)};\n`;
}
