import {bankRelease} from '../js/bank-release.js';
import {createHash} from 'node:crypto';

function canonical(value) {
  if(Array.isArray(value))return value.map(canonical);
  if(value&&typeof value==='object')return Object.fromEntries(Object.keys(value).sort().filter(k=>value[k]!==undefined).map(k=>[k,canonical(value[k])]));
  return value;
}
export function snapshotBanks(banks) {
  const snapshot={};
  banks.forEach((bank,type)=>{
    for(const question of bank){
      const {slot,variations,retired,reviewStatus,status,...template}=question;
      for(const [variation,content] of variations.entries()){
        // Challenge labels are selection metadata, not changes to the question or marking.
        delete template.challengeLevel;
        if(template.tags)template.tags=template.tags.filter(tag=>!tag.startsWith('challenge:'));
        const data=JSON.stringify(canonical({...template,...content}));
        snapshot[`${type}:${slot}:${variation}`]={fingerprint:createHash('sha256').update(data).digest('hex'),focus:question.focus,marks:content.parts.reduce((sum,p)=>sum+p.marks,0)};
      }
    }
  });
  return snapshot;
}
export function nextHistory(history,snapshot) {
  const latest=Math.max(...Object.keys(history).map(Number)),previous=history[latest];
  for(const key of Object.keys(snapshot)){
    const slot=key.slice(0,key.lastIndexOf(':')+1);
    const reusedSlot=!Object.keys(previous).some(address=>address.startsWith(slot))&&
      Object.values(history).some(revision=>Object.keys(revision).some(address=>address.startsWith(slot)));
    if(reusedSlot||!previous[key]&&Object.values(history).some(revision=>revision[key]))
      throw Error(`Cannot reuse removed question/variation address ${key}. Allocate a new slot instead.`);
  }
  // Additions at unused addresses cannot invalidate an existing valid code.
  const altered=Object.entries(previous).some(([key,digest])=>snapshot[key]?.fingerprint!==digest.fingerprint);
  const version=Math.max(altered?latest+1:latest,bankRelease.generation===0?bankRelease.firstEightBankVersion:0);
  if(version>63)throw Error('Question revision capacity reached. Run codes:update with --rollover-date=<UTC timestamp> to start a new generation.');
  return {...history,[version]:snapshot};
}
export function compatibilityModule(history) {
  const current=Math.max(...Object.keys(history).map(Number)),latest=history[current],deltas=[];
  let previous={};
  for(const [version,snapshot] of Object.entries(history)){
    // 1 = unchanged and available; 0 = changed or removed. Absent = never existed.
    const entries=Object.fromEntries(Object.entries(snapshot).map(([key,digest])=>[key,[latest[key]?.fingerprint===digest.fingerprint?1:0,digest.focus,digest.marks]]));
    const changes=Object.entries(entries).filter(([key,value])=>JSON.stringify(value)!==JSON.stringify(previous[key]));
    for(const key of Object.keys(previous))if(!(key in entries))changes.push([key,null]);
    deltas.push([Number(version),changes]);
    previous=entries;
  }
  // Preserve synchronous lookups without shipping every repeated historical snapshot.
  return `// Generated by scripts/question-codes.mjs. Do not edit by hand.
export const BANK_VERSION=${current};
const deltas=${JSON.stringify(deltas)};
const cache=new Map();
export const revisions={},revisionDetails={};
function restore(version){
  if(cache.has(version))return cache.get(version);
  const entries={};
  for(const [release,changes] of deltas){
    if(release>version)break;
    for(const [key,value] of changes){
      if(value===null)delete entries[key];
      else entries[key]=value;
    }
  }
  const states={},details={};
  for(const [key,[state,focus,marks]] of Object.entries(entries)){
    states[key]=state;
    details[key]=[focus,marks];
  }
  const restored={states,details};
  cache.set(version,restored);
  return restored;
}
for(const [version] of deltas){
  Object.defineProperty(revisions,version,{enumerable:true,get:()=>restore(version).states});
  Object.defineProperty(revisionDetails,version,{enumerable:true,get:()=>restore(version).details});
}
`;
}

export function rolloverHistory(history,snapshot,release,at){
  if(Math.max(...Object.keys(history).map(Number))!==63)throw Error('Rollover is allowed only after version 63.');
  const timestamp=Date.parse(at);
  if(!Number.isFinite(timestamp)||!String(at).endsWith('Z'))throw Error('Supply an explicit UTC rollover timestamp ending in Z.');
  if(release.latestRolloverAt&&timestamp<=Date.parse(release.latestRolloverAt))throw Error('Rollover date must increase.');
  return {history:{0:snapshot},release:{...release,generation:release.generation+1,latestRolloverAt:new Date(timestamp).toISOString()}};
}
